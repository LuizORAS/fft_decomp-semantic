#include "fft/battle_action.h"
#include "fft/battle_unit.h"
#include "psx/types.h"

/* Pick a chest's item: one of the dead unit's seven equipment slots at random, or with nothing
 * equipped a random consumable from Potion to Phoenix Down except Elixir. Outside execution (AI
 * simulation, preview) it returns no value (QUIRKS.md). */
u8 battle_unit_generate_treasure(battle_stats_t* unit) {
    u8 candidates[UNIT_EQUIPMENT_SLOT_COUNT];
    s32 count;
    s32 i;
    u32 item_id;

    if (g_battle_action_state != BATTLE_ACTION_STATE_EXECUTE) {
        return;
    }

    count = 0;
    for (i = 0; i < UNIT_EQUIPMENT_SLOT_COUNT; i++) {
        candidates[count] = unit->equipment[i];
        item_id = candidates[count];
        if (item_id >= ITEM_ID_END) {
            continue;
        }
        if (item_id == 0) {
            continue;
        }
        count++;
    }

    if (count == 0) {
        candidates[0] = ((rand() * 13) / 0x8000) - (ITEM_ID_COUNT - ITEM_ID_CONSUMABLE_FIRST);
        if (candidates[0] >= ITEM_ID_ELIXIR) {
            candidates[0] = candidates[0] + 1;
        }
        count = 1;
    }

    i = (rand() * count) / 0x8000;
    return candidates[i];
}
